//! Spectral-landmark fingerprinting (PLAN-SPECTRAL-FINGERPRINT-MATCHING §4, §6, §7).
//!
//! Pure-additive analysis module: takes canonical mono 48 kHz PCM and produces sparse spectral
//! PEAKS, the substrate the later boundaries turn into landmark hashes, a cached
//! `fingerprint-v1.cpf` artifact, batch lookup, and robust affine consensus. Nothing here
//! touches editor sync, audition, session, or export (§3).
//!
//! Boundaries 1–2 scope (this module today):
//!
//! - [`FingerprintFormatV1`] / [`FingerprintMatchParams`] — the §6 parameter contracts
//!   (`params`). The format is frozen via [`FingerprintFormatV1::fixed`]; the match params are
//!   defined but not yet consumed by any matching logic. [`FingerprintFormatV1::params_hash`]
//!   gives the §8.2 format hash ([`FIXED_PARAMS_HASH`] pins the frozen format's value).
//! - the deterministic 48k→12k half-band [`Downsampler`] (`downsample`), with checked-in FIR
//!   `coeffs` generated by `core/src/bin/gen_halfband.rs` and pinned by a golden test.
//! - the streaming, chunk-invariant [`FingerprintBuilder`] (`builder`): STFT + §7.3 spectral
//!   peak extraction (`peaks`), finalized into the §7.4 [`Landmark`] set (`landmarks`).
//! - §7.4 landmark generation + hash packing (`landmarks`): per-anchor fan-out target
//!   selection, the frozen 32-bit hash layout, and `(hash, anchor_frame)` ordering.
//! - §8.1 the versioned binary artifact (`file`): the little-endian `CPF1` encode and the
//!   rejecting [`FingerprintReader`] decode over a byte buffer (mmap-ready for boundary 3).
//!
//! Boundary 3 adds the versioned CACHE lifecycle (`cache`): the single PCM→`.cpf` builder
//! ([`build_artifact_bytes`]) shared by import-pass generation and the lazy build, plus
//! [`load_or_build`] (read-or-(re)build with atomic temp-rename). The track-side hook
//! (`CacheEntry::fingerprint_path_v1`, `TrackData.fingerprint`, `TrackData::fingerprint_v1`) lives
//! in `cache`/`track`.
//!
//! Boundary 4 adds the batch landmark lookup (`index`): the audios-side inverted index
//! [`AudioHashIndex`] built ONCE per `match_candidates` batch (§9.1, with per-track occurrence
//! suppression + [`IndexStats`] telemetry), and [`correspondences_for_pair`] (§9.2: the §9.1
//! occurrence-product guard, the `1/sqrt(occ_a·occ_b)` weight, frame-pair grouping with
//! `min(1.0, Σ)`, and the 128-bin time-stratified cap), producing [`PairCorrespondences`]. These
//! are deterministic building blocks that FEED boundary 5; they make NO classification decision.
//!
//! Boundary 5 adds the deterministic robust affine consensus (`robust_affine`): [`consensus`]
//! consumes the boundary-4 [`Correspondence`] slice (+ the candidate overlap) and fits the §10.1
//! affine map via §10.2 deterministic hypothesis generation (scale-1 smoothed-histogram peaks +
//! van-der-Corput two-point pairs), the §10.3 weighted score with the exact 7-level tie-break, the
//! §10.4 fixed-iteration Huber IRLS refinement (variance-floored, no NaN/Inf), and §10.5 runner-up
//! uniqueness / `score_margin`, returning an [`AffineConsensus`] with the §10.6 initial
//! [`AffineClass`] (`Match`/`Ambiguous`/`NoMatch`). It makes NO `PairEvidence` and calls NO existing
//! aligner (the IRLS is the consensus's OWN refinement over correspondences).
//!
//! Boundary 10 adds metadata time hints (`metadata_hint`): [`TimeHint`] parses container/BWF
//! metadata into an advisory scale-1 lag (§12.1) with a §12.2 [`HintReliability`], and
//! [`consensus_with_hint`] threads it into the SAME hypothesis list ([`consensus`] is the no-hint
//! wrapper). A rankable hint seeds ONE extra scale-1 hypothesis that competes on the unchanged §10.3
//! audio scoring (so it only wins by earning audio inliers), and an exact audio-score tie is ordered
//! toward the metadata-consistent candidate — but metadata NEVER lowers a threshold, restricts the
//! landmark lookup, or overrides a better audio hypothesis (§12.3, the non-vetoing guarantee).
//!
//! NOT yet present (boundary 11+): §13 graph consistency (the `graph_*` params), threshold
//! calibration, the default-matcher switch. This module never touches editor sync, audition,
//! session, or export (§3). `FingerprintMatchParams` is fully CONSUMED (the §9.1/§9.2 caps + the
//! §10 affine/score/threshold fields).

